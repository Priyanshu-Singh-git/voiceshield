"""Package VoiceShield code into a Kaggle GPU script kernel, push it, poll it, download outputs.

  python deploy/kaggle_job.py push  <name> -- <shell commands run on Kaggle, '{ROOT}' = dataset LA root>
  python deploy/kaggle_job.py status <name>
  python deploy/kaggle_job.py pull  <name>          # -> kaggle_runs/<name>/
The dataset (awsaf49/asvpoof-2019-dataset, official ASVspoof 2019 layout) is attached read-only; nothing is uploaded.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = r"F:\tools\uv\bin\kaggle.exe"
USER = "priyanshusingh308"
DATASET = "awsaf49/asvpoof-2019-dataset"
FILES = ["src/voiceshield/__init__.py", "src/voiceshield/data.py", "src/voiceshield/features.py",
         "src/voiceshield/metrics.py", "src/voiceshield/models.py", "train/train_cm.py", "eval/probe_speed.py"]

TEMPLATE = r'''# Auto-generated by deploy/kaggle_job.py: writes the VoiceShield package, then runs the job.
import json, os, subprocess, sys, glob
from pathlib import Path
FILES = json.loads({files!r})
W = Path("/kaggle/working/vs")
for rel, txt in FILES.items():
    p = W / rel; p.parent.mkdir(parents=True, exist_ok=True); p.write_text(txt)
CANDIDATES = ["/kaggle/input/datasets/awsaf49/asvpoof-2019-dataset/LA/LA", "/kaggle/input/asvpoof-2019-dataset/LA/LA"]
LA_ROOT = next((c for c in CANDIDATES if os.path.isdir(c + "/ASVspoof2019_LA_cm_protocols")), None)
if LA_ROOT is None:  # slow fallback: walk the mounted inputs
    LA_ROOT = str(Path(glob.glob("/kaggle/input/**/ASVspoof2019_LA_cm_protocols", recursive=True)[0]).parent)
import torch
print("CUDA available:", torch.cuda.is_available(), flush=True)
assert torch.cuda.is_available(), "No GPU attached: is the Kaggle account phone-verified and GPU quota left?"
print("LA root:", LA_ROOT, flush=True)
subprocess.run("nvidia-smi", shell=True)
for cmd in json.loads({cmds!r}):
    cmd = cmd.replace("{{ROOT}}", LA_ROOT)
    print(">>>", cmd, flush=True)
    r = subprocess.run(cmd, shell=True, cwd=str(W))
    print("<<< exit", r.returncode, flush=True)
'''


def kaggle(*args, check=True):
    r = subprocess.run([KAGGLE, *args], capture_output=True, text=True)
    if check and r.returncode != 0:
        raise SystemExit(r.stdout + r.stderr)
    return r.stdout + r.stderr


def push(name, cmds):
    d = ROOT / "kaggle_jobs" / name
    d.mkdir(parents=True, exist_ok=True)
    files = {f: (ROOT / f).read_text(encoding="utf-8") for f in FILES if (ROOT / f).exists()}
    (d / "run.py").write_text(TEMPLATE.format(files=json.dumps(files), cmds=json.dumps(cmds)), encoding="utf-8")
    (d / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{USER}/{name}", "title": name, "code_file": "run.py", "language": "python", "kernel_type": "script",
        "is_private": True, "enable_gpu": True, "enable_internet": True, "dataset_sources": [DATASET],
        "competition_sources": [], "kernel_sources": [], "machine_shape": "NvidiaTeslaT4"}, indent=2))
    print(kaggle("kernels", "push", "-p", str(d)))


def main():
    op, name = sys.argv[1], sys.argv[2]
    if op == "push":
        cmds = sys.argv[sys.argv.index("--") + 1:]
        push(name, cmds)
    elif op == "status":
        print(kaggle("kernels", "status", f"{USER}/{name}"))
    elif op == "pull":
        out = ROOT / "kaggle_runs" / name
        out.mkdir(parents=True, exist_ok=True)
        print(kaggle("kernels", "output", f"{USER}/{name}", "-p", str(out), check=False))


if __name__ == "__main__":
    main()
